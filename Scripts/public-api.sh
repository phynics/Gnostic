#!/usr/bin/env bash
# Compares the public API of the stable products against the committed
# baseline, or rewrites the baseline (#676).
#
#   Scripts/public-api.sh check    fail with a diff when the API differs
#   Scripts/public-api.sh update   rewrite the baseline from the compiler
#
# Run it through `make api-check` and `make api-update`, which start the pinned
# development container. The API text is the compiler's own `.swiftinterface`
# output, so it covers every public declaration the compiler exports: members
# of a public extension, multi-line typealiases, `@_exported import`, default
# arguments and attributes. It is not a scan of source text.
#
# The text names Foundation types as `FoundationEssentials::UUID` on Linux and
# `Foundation::UUID` on macOS, so the baseline is the Linux output and the
# check runs on Linux only (the pinned container).
set -euo pipefail

mode=${1:-check}
case $mode in check|update) ;; *) echo "usage: $0 check|update" >&2; exit 2 ;; esac

root=${WORKSPACE_ROOT:-/workspace}
baseline_dir=$root/Documentation/Compatibility/API
products=(GnosticProtocol GnosticClient)
# A separate scratch path keeps the interface build from invalidating the
# normal build, which `-Xswiftc -emit-module-interface` would otherwise force.
# The compiler warns that interfaces need library evolution. Library evolution
# does not build the dependency graph (swift-crypto), and without it the
# interface still lists every public declaration, so the warning is suppressed
# here. The normal build keeps its warnings-as-errors.
scratch=$root/.build/api-interface
# shellcheck disable=SC2206 # SWIFT_FLAGS is a space-separated argument list.
swift_flags=(${SWIFT_FLAGS:---cache-path $root/.swiftpm-cache --disable-automatic-resolution --build-system native})

cd "$root"
for product in "${products[@]}"; do
    swift build "${swift_flags[@]}" --quiet --scratch-path "$scratch" \
        --target "$product" -Xswiftc -emit-module-interface -Xswiftc -suppress-warnings
done
bin_path=$(swift build "${swift_flags[@]}" --scratch-path "$scratch" --show-bin-path 2>/dev/null)

private_stored_property='^[[:space:]]+(@[^[:space:]]+[[:space:]]+)*((final|static|lazy|weak|nonisolated)[[:space:]]+)*(private|fileprivate)[[:space:]]+(let|var)[[:space:]]'
output=$(mktemp -d)
trap 'rm -rf "$output"' EXIT

for product in "${products[@]}"; do
    interface=$bin_path/$product.build/$product.swiftinterface
    test -f "$interface" || { echo "The compiler wrote no $interface" >&2; exit 1; }
    # Drop the `// swift-*` header: it names the compiler build and the
    # package name, which vary with the toolchain and checkout and are not API.
    # Without library evolution the compiler also prints the private stored
    # properties of public types, because they affect layout. They are not API,
    # so the filter drops them; the check below fails if any private text is
    # left.
    {
        echo "// Public API of $product. Generated by Scripts/public-api.sh; do not edit."
        echo "// Regenerate with: make api-update"
        grep -v '^// swift-' "$interface" \
            | grep -vE "$private_stored_property" || true
    } > "$output/$product.swiftinterface"
    if grep -nE '(^|[[:space:]])(private|fileprivate)([[:space:]]|\()' "$output/$product.swiftinterface" >&2; then
        echo "The API text for $product still contains private declarations; extend the filter in Scripts/public-api.sh." >&2
        exit 1
    fi
    if grep -nE '/(workspace|tmp|home|root|Users)/' "$output/$product.swiftinterface" >&2; then
        echo "The API text for $product contains an absolute path; the baseline would not be deterministic." >&2
        exit 1
    fi
done

if [ "$mode" = update ]; then
    mkdir -p "$baseline_dir"
    for product in "${products[@]}"; do
        cp "$output/$product.swiftinterface" "$baseline_dir/$product.swiftinterface"
    done
    echo "Wrote the public API baseline to Documentation/Compatibility/API/"
    exit 0
fi

failed=0
for product in "${products[@]}"; do
    baseline=$baseline_dir/$product.swiftinterface
    if [ ! -f "$baseline" ]; then
        echo "Missing baseline: Documentation/Compatibility/API/$product.swiftinterface" >&2
        failed=1
        continue
    fi
    if ! diff -u --label "baseline/$product.swiftinterface" --label "current/$product.swiftinterface" \
        "$baseline" "$output/$product.swiftinterface"; then
        failed=1
    fi
done

if [ "$failed" != 0 ]; then
    cat >&2 <<'MESSAGE'

The public API of GnosticProtocol or GnosticClient differs from the committed
baseline (diff above: "-" is the baseline, "+" is the current build).

If the change is deliberate, regenerate the baseline and commit it:

    make api-update

A baseline change makes the pull request review-required (AGENTS.md, "Review
and finish"). See Documentation/Compatibility/API/README.md.
MESSAGE
    exit 1
fi
echo "Public API of ${products[*]} matches the baseline."
